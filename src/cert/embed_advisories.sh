#!/bin/sh
# Writes the advisories given as arguments after $1 to the C++ file $1, as
# `kBuiltin`, one raw string per advisory (Advisory.cpp, ADR 0073).
out=$1
shift
{
  echo "// Generated by src/cert/embed_advisories.sh from security/advisories."
  echo "const char *const kBuiltin[] = {"
  for f in "$@"; do
    if grep -q ')pia_advisory"' "$f"; then
      echo "embed_advisories.sh: $f holds the delimiter" >&2
      exit 1
    fi
    printf 'R"pia_advisory('
    cat "$f"
    printf ')pia_advisory",\n'
  done
  echo "nullptr};"
} > "$out"
