#!/usr/bin/env python3
"""Writes tests/std/Inputs/tokenizer_cases.h: texts for Pia.Llm.Tokenizer,
each with the ids llama2.c's run.c gives it under tok512, the stories260K
tokenizer (ADR 0067).

The ids come from a real run of run.c, built with tokenizer_ref.c:

  curl -LO https://raw.githubusercontent.com/karpathy/llama2.c/master/run.c
  cc -O2 -w -o tokenizer_ref tests/std/Inputs/tokenizer_ref.c -I. -lm
  python3 tests/std/Inputs/tokenizer_gen.py ./tokenizer_ref \\
      tests/std/Inputs/tok512.bin > tests/std/Inputs/tokenizer_cases.h
  clang-format -i tests/std/Inputs/tokenizer_cases.h

run.c reads a text up to its first NUL, so no text holds one."""

import subprocess
import sys

TEXTS = [
    ("a TinyStories sentence", "Once upon a time, there was a little girl named Lily.".encode()),
    ("the empty text", b""),
    ("one letter", b"a"),
    ("one space", b" "),
    ("three spaces", b"   "),
    ("a newline and a tab", b"She smiled.\n\tThe end."),
    ("digits and punctuation", b"1, 2, 3... 42! (x+y)=z?"),
    ("curly quotes and a dash, pieces of three bytes", "“Hi!” she said — “bye.”".encode()),
    ("an accent, a piece of two bytes", "Café crème".encode()),
    ("an emoji, four bytes with no piece", "I \U0001F600 you".encode()),
    ("a character with no piece, three bytes", "中文".encode()),
    ("stray continuation bytes", b"a\x80\x80b"),
    ("five continuation bytes after a lead byte", b"\xf0\x80\x80\x80\x80\x80z"),
    ("a lone lead byte at the end", b"ok\xe2"),
    ("control bytes", b"\x01\x02\x7f"),
    ("text that looks like a byte piece", b"<0x41> and <s>"),
    ("a capitalised word", b"The Dog RAN"),
    ("a longer story", ("Tom and Sue went to the park. They saw a big red ball. "
                        "Tom kicked the ball and it flew up high. Sue laughed and "
                        "ran after it. \"Catch it!\" said Tom. They played all day "
                        "until the sun went down, and then they went home happy.").encode()),
]


def run_ref(ref, tok):
    hexes = "".join(t.hex() + "\n" for _, t in TEXTS)
    out = subprocess.run([ref, tok, "512"], input=hexes.encode(), check=True,
                         capture_output=True).stdout.decode().splitlines()
    assert len(out) == len(TEXTS)
    return [[int(x) for x in line.split()] for line in out]


def carr(xs):
    return "{" + ", ".join(str(x) for x in xs) + "}"


def main():
    ref, tok = sys.argv[1], sys.argv[2]
    ids = run_ref(ref, tok)
    print("""// The texts of tokenizer_run_main.c, each with the ids llama2.c's run.c
// gives it under tok512 with <s>. Generated by
// tests/std/Inputs/tokenizer_gen.py from a run of run.c; do not edit.

#include <stdint.h>
""")
    for k, ((what, text), want) in enumerate(zip(TEXTS, ids)):
        print(f"// {what}")
        print(f"static const uint8_t text{k}[] = {carr(list(text) or [0])};")
        print(f"static const uint32_t ids{k}[] = {carr(want)};")
    print("""
struct tokenizer_case {
  const char *what;
  const uint8_t *text;
  uint64_t text_len;
  const uint32_t *ids;
  uint64_t ids_len;
};

static const struct tokenizer_case kCases[] = {""")
    for k, ((what, text), want) in enumerate(zip(TEXTS, ids)):
        print(f'    {{"{what}", text{k}, {len(text)}, ids{k}, {len(want)}}},')
    print("""};""")


if __name__ == "__main__":
    main()
