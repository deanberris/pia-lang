#!/usr/bin/env python3
"""Writes tests/std/Inputs/gif_lzw_run.pia: LZW streams and the indices
giflib decodes from them, for Pia.Image.Gif.Lzw's differential run test.

    cc -I/opt/homebrew/include -L/opt/homebrew/lib -o /tmp/gif_ref \
        tests/std/Inputs/gif_ref.c -lgif
    python3 tests/std/Inputs/gif_lzw_gen.py tests/std/Inputs/gif_lzw_run.pia \
        /tmp/gif_ref /tmp/gif_lzw

giflib's encoder writes three of the streams; this script's own encoder
writes two that giflib's encoder cannot (a full dictionary that is never
cleared, and long runs), and each is checked to decode with giflib to the
pixels it encodes. Every expected index sequence is giflib's DGifSlurp
output.
"""
import struct, subprocess, sys, os
D = os.path.dirname(os.path.abspath(__file__))
REF = sys.argv[2]

def lzw_encode(px, m, clear_when_full):
    clear = 1 << m; eoi = clear + 1
    codes = []
    def reset():
        return {}, clear + 2
    d, nx = reset()
    codes.append(clear)
    w = (px[0],)
    for c in px[1:]:
        wc = w + (c,)
        if wc in d:
            w = wc; continue
        codes.append(w[0] if len(w) == 1 else d[w])
        if nx < 4096:
            d[wc] = nx; nx += 1
        elif clear_when_full:
            codes.append(clear); d, nx = reset()
        w = (c,)
    codes.append(w[0] if len(w) == 1 else d[w])
    codes.append(eoi)
    # widths as the decoder reads them
    bits = []
    width = m + 1; dnx = clear + 2; prev = None
    for code in codes:
        bits.append((code, width))
        if code == clear:
            width = m + 1; dnx = clear + 2; prev = None; continue
        if code == eoi: break
        if prev is not None and dnx < 4096:
            dnx += 1
        prev = code
        if dnx == (1 << width) and width < 12: width += 1
    acc = 0; n = 0; out = bytearray()
    for code, wd in bits:
        acc |= code << n; n += wd
        while n >= 8: out.append(acc & 0xFF); acc >>= 8; n -= 8
    if n: out.append(acc & 0xFF)
    return bytes(out)

def write_gif(path, w, h, m, data):
    bits = max(m, 1)
    g = bytearray(b'GIF89a') + struct.pack('<HHBBB', w, h, 0x80 | (bits - 1), 0, 0)
    for i in range(1 << bits): g += bytes([i, i, i])
    g += b'\x2c' + struct.pack('<HHHHB', 0, 0, w, h, 0) + bytes([m])
    for i in range(0, len(data), 255):
        ch = data[i:i + 255]; g += bytes([len(ch)]) + ch
    g += b'\x00\x3b'
    open(path, 'wb').write(g)

def extract(path):
    g = open(path, 'rb').read()
    p = 13
    if g[10] & 0x80: p += 3 * (2 << (g[10] & 7))
    while True:
        b = g[p]
        if b == 0x21:
            p += 2
            while g[p]: p += 1 + g[p]
            p += 1
        elif b == 0x2c:
            flags = g[p + 9]; p += 10
            if flags & 0x80: p += 3 * (2 << (flags & 7))
            m = g[p]; p += 1; data = bytearray()
            while g[p]: data += g[p + 1:p + 1 + g[p]]; p += 1 + g[p]
            return m, bytes(data)
        else: raise SystemExit('bad block')

def giflib_decode(path, n):
    o = path + '.idx'
    subprocess.check_call([REF, 'dec', path, o])
    r = open(o, 'rb').read(); assert len(r) == n
    return r

def lcg(n, mod, seed=12345):
    x = seed; r = []
    for _ in range(n):
        x = (x * 1103515245 + 12345) & 0x7fffffff; r.append((x >> 16) % mod)
    return r

cases = []
tmp = sys.argv[3]; os.makedirs(tmp, exist_ok=True)
def giflib_case(name, w, h, bits, px):
    i = os.path.join(tmp, name + '.raw'); open(i, 'wb').write(bytes(px))
    g = os.path.join(tmp, name + '.gif')
    subprocess.check_call([REF, 'enc', str(w), str(h), str(bits), i, g])
    m, data = extract(g)
    cases.append((name, m, data, giflib_decode(g, w * h)))
def own_case(name, w, h, m, px, clear_when_full):
    data = lzw_encode(px, m, clear_when_full)
    g = os.path.join(tmp, name + '.gif'); write_gif(g, w, h, m, data)
    m2, data2 = extract(g); assert data2 == data
    exp = giflib_decode(g, w * h); assert exp == bytes(px), name
    cases.append((name, m, data, exp))

giflib_case('two_bit', 16, 16, 2, [(x * y) % 4 for y in range(16) for x in range(16)])
giflib_case('one_bit', 24, 8, 1, [(x ^ y) & 1 for y in range(8) for x in range(24)])
giflib_case('noise8', 96, 96, 8, lcg(96 * 96, 256))
own_case('deferred', 128, 48, 8, lcg(128 * 48, 256, 7), False)
own_case('runs', 64, 16, 3, [(i // 37) % 8 for i in range(64 * 16)], False)

def arr(name, ty, xs):
    return 'let %s : [%s; %d] = [%s]\n' % (name, ty, len(xs), '; '.join(map(str, xs)))
out = open(sys.argv[1], 'w')
out.write('''(* Runs Pia.Image.Gif.Lzw's compiled code on LZW streams, linked by
   pia_binary: 0 when each decodes to the indices giflib decodes from the
   same GIF, and otherwise the number of the first wrong one. The streams
   and indices are generated by tests/std/Inputs/gif_lzw_gen.py: two_bit,
   one_bit and noise8 are written by giflib's encoder (noise8 fills the
   dictionary, and giflib clears it), deferred fills the dictionary and
   never clears it, and runs is long runs, so most codes are the KwKwK case.
   Every expected index sequence is giflib's DGifSlurp output. *)
import Pia.Image.Bits.Bits as B
import Pia.Image.Gif.Spec.Lzw as S
import Pia.Image.Gif.Lzw.Lzw as L

''')
for name, m, data, exp in cases:
    out.write(arr(name + '_s', 'u8', list(data)))
    out.write(arr(name + '_e', 'u8', list(exp)))
out.write('''
(* 0 when s decodes to exactly e. *)
let check (s : [u8]) (e : [u8]) (m : int{2..8}) (t : borrowed inout mutable [u8]) (o : borrowed inout mutable [u8]) : bool
  requires len t = 12288
= match L.decode s m t o with
  | Ok n -> (
      if n <> len e then false
      else (
        let bad : mutable usize = 0 in
        for i in 0 .. n do
          if o.[i] <> e.[i] then bad <- 1 else ()
        done;
        bad = 0))
  | Err _ -> false

(* A truncated stream, and an output one index too short. *)
let failures (s : [u8]) (t : borrowed inout mutable [u8]) (o : borrowed inout mutable [u8]) : i32
  requires len t = 12288 && len s > 4
= let cut = s.[0 .. len s - 4] in
  match L.decode cut 8 t o with
  | Ok _ -> 1
  | Err e -> (match e with | Truncated _ -> 0 | _ -> 2)

let full (s : [u8]) (t : borrowed inout mutable [u8]) (o : borrowed inout mutable [u8]) : i32
  requires len t = 12288
= match L.decode s 2 t o with
  | Ok _ -> 1
  | Err e -> (match e with | OutputFull _ -> 0 | _ -> 2)

let run (mem : borrowed inout mutable [u8]) : i32
  requires len mem = %d
= let t = mem.[0 .. 12288] in
  let o = mem.[12288 .. len mem] in
''' % (12288 + max(len(c[3]) for c in cases)))
for i, (name, m, data, exp) in enumerate(cases):
    out.write('  if check %s_s %s_e %d t o = false then %d else\n' % (name, name, m, i + 1))
n = len(cases)
out.write('  if failures noise8_s t o <> 0 then %d else\n' % (n + 1))
out.write('  if full two_bit_s t (o.[0 .. 255]) <> 0 then %d else\n' % (n + 2))
out.write('  0\n\nlet main () : i32 = with_arena %d (let (a) => run a.mem)\n' % (12288 + max(len(c[3]) for c in cases)))
print([(c[0], c[1], len(c[2]), len(c[3])) for c in cases])
