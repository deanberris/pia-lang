#!/usr/bin/env python3
"""Writes tests/std/Inputs/zlib_run.pia: zlib and raw deflate streams made
by zlib (through Python's zlib module) at several levels and strategies,
with the length and FNV-1a hash of what each decompresses to, for the
differential run test of Pia.Compress.Inflate and Pia.Compress.Zlib.

    python3 tests/std/Inputs/zlib_gen.py tests/std/Inputs/zlib_run.pia
"""
import random, sys, zlib

def fnv(b):
    h = 2166136261
    for x in b: h = ((h ^ x) * 16777619) & 0xffffffff
    return h

rnd = random.Random(54)
text = (b"Pia proves its programs before it compiles them. " * 40) + bytes(range(32, 127)) * 8
noise = bytes(rnd.randrange(256) for _ in range(3000))
runs = b"".join(bytes([c]) * rnd.randrange(1, 300) for c in b"abcabcxyz" * 40)
far = noise[:1500] + bytes(40000) + noise[:1500]   # 41500 back: outside the window
wide = bytes(rnd.randrange(256) for _ in range(30000))
window = wide + wide[:3000]                          # matches 30000 back
mid = noise[:2000] + text + noise[:2000]
cases = []
def z(name, data, level, strategy=zlib.Z_DEFAULT_STRATEGY, wbits=15):
    c = zlib.compressobj(level, zlib.DEFLATED, wbits, 9, strategy)
    out = c.compress(data) + c.flush()
    assert zlib.decompress(out, wbits) == data
    cases.append((name, out, len(data), fnv(data), wbits > 0))
z('empty', b'', 6)
z('text_stored', text, 0)
z('text_fast', text, 1)
z('text_best', text, 9)
z('text_fixed', text, 9, zlib.Z_FIXED)
z('noise', noise, 9)
z('runs', runs, 6)
z('runs_rle', runs, 6, zlib.Z_RLE)
z('mid', mid, 9)
z('far', far, 9)
z('window', window, 9)
z('raw_text', text, 6, wbits=-15)
z('raw_fixed', runs, 6, zlib.Z_FIXED, wbits=-15)

def arr(name, xs):
    return 'let %s : [u8; %d] = [%s]\n' % (name, len(xs), '; '.join(map(str, xs)))

o = open(sys.argv[1], 'w')
o.write('''(* Runs Pia.Compress.Zlib's and Pia.Compress.Inflate's compiled code,
   linked by pia_binary: 0 when every stream zlib made (generated by
   tests/std/Inputs/zlib_gen.py: stored, fast, best, fixed-Huffman and RLE
   compression of text, noise, runs and long-distance data, as zlib and as
   raw deflate) decompresses to the length and FNV-1a hash of zlib's own
   output, when every truncation of each zlib stream is an error, when a
   changed Adler-32 is ZChecksum, and when every one-byte corruption of a
   stream decodes or fails without crashing; otherwise the number of the
   first wrong check. *)
import Pia.Image.Bits.Bits as B
import Pia.Compress.Huffman.Huffman as H
import Pia.Compress.Inflate.Spec.Deflate as F
import Pia.Compress.Inflate.Inflate as I
import Pia.Compress.Zlib.Zlib as Z

''')
for name, data, n, h, isz in cases:
    o.write(arr(name, list(data)))
o.write(r'''
(* FNV-1a over the first n bytes of b. *)
let fnv (b : [u8]) (n : usize) : u32 @overflow(wrap)
  requires n <= len b
= let h : mutable u32 = 2166136261 in
  for i in 0 .. n do
    let x : u32 = b.[i] in
    h <- (h ^ x) * 16777619
  done;
  h

(* The zlib stream s decompresses to n bytes hashing to want. *)
let zlib_is (s : [u8]) (n : usize) (want : u32) (m : borrowed inout mutable [u8]) : bool
  requires len m = 131072
= if len s > 65536 then false
  else (
    let dst = m.[0 .. 65536] in
    match Z.decompress s dst (m.[65536 .. 65856]) (m.[66560 .. 67264]) (m.[67584 .. 68288]) with
    | Ok r -> r.n = n && fnv (m.[0 .. 65536]) r.n = want
    | Err _ -> false)

(* The raw deflate stream s decompresses to n bytes hashing to want. *)
let raw_is (s : [u8]) (n : usize) (want : u32) (m : borrowed inout mutable [u8]) : bool
  requires len m = 131072
= if len s > 65536 then false
  else (
    let dst = m.[0 .. 65536] in
    match I.inflate s 0 dst (m.[65536 .. 65856]) (m.[66560 .. 67264]) (m.[67584 .. 68288]) with
    | Ok r -> r.written = n && fnv (m.[0 .. 65536]) r.written = want
    | Err _ -> false)

(* Every prefix of s shorter than s fails. *)
let truncations (s : [u8]) (m : borrowed inout mutable [u8]) : bool
  requires len m = 131072 && len s <= 65536
= let bad : mutable bool = false in
  for k in 0 .. len s do
    match Z.decompress (s.[0 .. k]) (m.[0 .. 65536]) (m.[65536 .. 65856]) (m.[66560 .. 67264]) (m.[67584 .. 68288]) with
    | Ok _ -> bad <- true
    | Err _ -> ()
  done;
  bad = false

(* s with its last byte changed is ZChecksum; c is the copy. *)
let checksum_caught (s : [u8]) (c : borrowed inout mutable [u8]) (m : borrowed inout mutable [u8]) : bool
  requires len m = 131072 && len c = len s && len s > 0 && len s <= 65536
= for j in 0 .. len s do c.[j] <- s.[j] done;
  c.[len s - 1] <- c.[len s - 1] ^ 1;
  match Z.decompress c (m.[0 .. 65536]) (m.[65536 .. 65856]) (m.[66560 .. 67264]) (m.[67584 .. 68288]) with
  | Ok _ -> false
  | Err e -> (match e with | ZChecksum _ -> true | _ -> false)

(* s with each byte flipped in turn decodes or fails, never crashing;
   returns how many of them still decoded. *)
let flips (s : [u8]) (c : borrowed inout mutable [u8]) (m : borrowed inout mutable [u8]) : usize
  requires len m = 131072 && len c = len s && len s <= 65536
= let ok : mutable usize = 0 in
  for p in 0 .. len s
    invariant ok <= p
  do
    for j in 0 .. len s do c.[j] <- s.[j] done;
    c.[p] <- c.[p] ^ 0xFF;
    match Z.decompress c (m.[0 .. 65536]) (m.[65536 .. 65856]) (m.[66560 .. 67264]) (m.[67584 .. 68288]) with
    | Ok _ -> ok <- ok + 1
    | Err _ -> ()
  done;
  ok

let run (m : borrowed inout mutable [u8]) (c : borrowed inout mutable [u8]) : i32
  requires len m = 131072 && len c = 65536
= ''')
i = 1
for name, data, n, h, isz in cases:
    f = 'zlib_is' if isz else 'raw_is'
    o.write('if %s %s %d %d m = false then %d else\n  ' % (f, name, n, h, i)); i += 1
o.write('if truncations text_best m = false then %d else\n  ' % i); i += 1
o.write('if truncations text_fixed m = false then %d else\n  ' % i); i += 1
o.write('if truncations text_stored m = false then %d else\n  ' % i); i += 1
o.write('if checksum_caught runs (c.[0 .. len runs]) m = false then %d else\n  ' % i); i += 1
o.write('if flips text_best (c.[0 .. len text_best]) m > len text_best then %d else\n  ' % i); i += 1
o.write('if flips runs (c.[0 .. len runs]) m > len runs then %d else\n  ' % i); i += 1
o.write('0\n\nlet main () : i32 = with_arena 196608 (let (a) => run (a.mem.[0 .. 131072]) (a.mem.[131072 .. 196608]))\n')
for name, data, n, h, isz in cases: print(name, len(data), n)
